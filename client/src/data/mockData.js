export function getStudent(id) {
  return students.find((s) => s.id === id) || students[0];
}

export function getResource(id) {
  return resources.find((r) => r.id === id) || resources[0];
}

export function findMatchingKit(query) {
  const lower = query.toLowerCase();
  const matched = intentMappings.find((mapping) =>
    mapping.keywords.some((kw) => lower.includes(kw))
  );
  const kit = matched || intentMappings[0];
  return {
    ...kit,
    resources: kit.resourceIds.map((id) => getResource(id)).filter(Boolean),
  };
}
